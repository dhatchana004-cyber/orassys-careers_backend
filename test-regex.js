const phones = [
  "+91 98765 43210",
  "9876543210",
  "09876543210",
  "+91-98765-43210",
  "(123) 456-7890",
  "+1 123 456 7890"
];

const regex = /(?:\+?\d{1,3}[\s.-]?)?(?:\(?\d{3}\)?[\s.-]?)?\d{3}[\s.-]?\d{4}|(?:(?:\+|0{0,2})91[\s.-]?)?[6789](?:[\s.-]?\d){9}/;

phones.forEach(p => {
  const match = p.match(regex);
  console.log(p, '=>', match ? match[0] : null);
});
